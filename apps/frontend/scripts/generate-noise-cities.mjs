/**
 * Write the city list the noise tiles are built for.
 *
 * apps/noise needs to know where each city is and how far around it to model,
 * and CITIES in src/seo/cities.ts already says both. Rather than keep a second
 * list in sync by hand — the failure mode being a city that has pages and no
 * tiles, silently — this generates the one apps/noise reads, the same way
 * generate-osmium-filter.mjs generates the tag filter.
 *
 *   node scripts/generate-noise-cities.mjs            write the file
 *   node scripts/generate-noise-cities.mjs --check    fail if it is stale
 *
 * Every tier by default, which it did not used to be. This file is the
 * catalogue of areas that *can* be built, and something else decides which
 * ones are: apps/noise/areas.txt, chosen from real usage and from how many
 * noise-relevant points a city has rather than from the SEO tiering here.
 *
 * Narrowing this to tier 1 was what made the two disagree — the deploy list
 * named Hamburg and Stuttgart and the builder answered "no such city in
 * cities.json", because the tiering that ranks search impressions is not the
 * one that ranks a map overlay. A catalogue costs 148 rows of JSON; the tiles
 * are what cost anything, and areas.txt is where that is decided.
 *
 * NOISE_TIERS still narrows it, for a checkout that wants a smaller catalogue.
 */
import { readFile, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import path from "node:path";
import { createServer } from "vite";

const ROOT = path.resolve(import.meta.dirname, "..");
const OUTPUT = path.resolve(ROOT, "..", "noise", "cities.json");

/**
 * Which tiers to write. Read from the environment rather than a flag so that
 * the compose file can set it in one place and both this and the builder agree
 */
const TIERS = new Set(
  (process.env.NOISE_TIERS ?? "1,2,3")
    .split(",")
    .map(tier => Number(tier.trim()))
    .filter(tier => tier >= 1 && tier <= 3)
);

async function loadCities() {
  const server = await createServer({
    root: ROOT,
    server: { middlewareMode: true },
    appType: "custom",
    logLevel: "error",
  });
  try {
    const module = await server.ssrLoadModule("/src/seo/cities.ts");
    return { cities: module.CITIES, defaultRadius: module.DEFAULT_CITY_RADIUS };
  } finally {
    await server.close();
  }
}

async function main() {
  const { cities, defaultRadius } = await loadCities();

  const selected = cities
    .filter(city => TIERS.has(city.tier))
    .map(city => ({
      slug: city.slug,
      name: city.name,
      countryCode: city.countryCode,
      lat: city.lat,
      lon: city.lon,
      // The same radius the prerendered POI list covers, so a page and the
      // noise under it describe the same area. A city that needs a wider net
      // for its points needs one for its roads too
      radius: city.radius ?? defaultRadius,
    }))
    .sort((a, b) => a.slug.localeCompare(b.slug));

  const content = `${JSON.stringify(
    {
      _comment:
        "Generated by apps/frontend/scripts/generate-noise-cities.mjs from " +
        "src/seo/cities.ts. Do not edit by hand: run `npm run noise:cities`.",
      tiers: [...TIERS].sort(),
      cities: selected,
    },
    null,
    2
  )}\n`;

  const previous = existsSync(OUTPUT) ? await readFile(OUTPUT, "utf8") : null;

  if (process.argv.includes("--check")) {
    if (previous !== content) {
      console.error(
        `${path.relative(process.cwd(), OUTPUT)} is out of date with CITIES. ` +
          "Run `npm run noise:cities`."
      );
      process.exit(1);
    }
    console.log("Noise city list is up to date.");
    return;
  }

  await writeFile(OUTPUT, content);
  console.log(
    `${previous === content ? "Unchanged" : "Wrote"} ${path.relative(
      process.cwd(),
      OUTPUT
    )} (${selected.length} cities)`
  );
}

main().catch(error => {
  console.error(error);
  process.exit(1);
});
